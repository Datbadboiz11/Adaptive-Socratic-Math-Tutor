"""Generate public response types from Pydantic schemas; no private authoring models."""
import argparse
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT / 'backend'))
from app.session_contracts import SessionView,TopicView,TurnResult,Report,TeachingTurnRequest


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/',1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'],ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(v,ensure_ascii=False) for v in schema['enum'])
    if 'anyOf' in schema:
        return '('+' | '.join(ts(item) for item in schema['anyOf'])+')'
    kind=schema.get('type')
    if kind=='null': return 'null'
    if kind=='string': return 'string'
    if kind in ('integer','number'): return 'number'
    if kind=='boolean': return 'boolean'
    if kind=='array': return 'Array<'+ts(schema['items'])+'>'
    if kind=='object':
        if not schema.get('properties'):
            additional=schema.get('additionalProperties',{})
            return 'Record<string, '+(ts(additional) if isinstance(additional,dict) else 'unknown')+'>'
        return '{ '+ '; '.join(json.dumps(key)+': '+ts(value) for key,value in schema['properties'].items())+' }'
    return 'unknown'


def render():
    schemas={}
    for model in (SessionView,TopicView,TurnResult,Report,TeachingTurnRequest):
        schema=model.model_json_schema()
        schemas.update(schema.pop('$defs',{}))
        schemas[model.__name__]=schema
    return ('// Generated by scripts/exports/export_frontend_types.py; do not edit.\n'
            '// Response models include server defaults. UUID/datetime fields are JSON strings.\n'
            +'\n'.join('export type '+name+' = '+ts(schema)+';' for name,schema in sorted(schemas.items()))+'\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    path=ROOT / 'frontend/app/lib/api-types.ts'
    expected=render()
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8')!=expected:
            raise SystemExit('Frontend public types are stale; run export_frontend_types.py')
    else:
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text(expected,encoding='utf-8')
    print('PASS: public frontend types match backend contracts')


if __name__=='__main__': main()
